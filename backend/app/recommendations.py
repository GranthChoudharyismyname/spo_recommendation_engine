def _rule_layout(b: _Builder) -> None:
    metrics = b.result.get("spo_layout_metrics", {}) or {}
    structural = int(b.result.get("structural_score", 0) or 0)
    headroom = _structural_headroom(structural)
    if structural >= 95:
        return

    # Each component's measured cost, so a finding can say what it actually cost rather
    # than splitting the headroom evenly across every violation.
    # Where each layout problem is visible, measured from the same spans that produced
    # the score. A layout finding has no sentence to search for, so without this it is
    # the one kind of finding that can never point at anything.
    regions = b.result.get("spo_layout_regions") or {}
    breakdown = b.result.get("structural_breakdown") or {}
    cost_by_key = {
        c["key"]: c
        for c in breakdown.get("components", [])
        if isinstance(c, dict) and "key" in c
    }

    for key, rule, title, action in _LAYOUT_RULES:
        metric = metrics.get(key) or cost_by_key.get(key, {}).get("metric")
        if not isinstance(metric, dict):
            continue
        delta = metric.get("DELTA")
        if not isinstance(delta, (int, float)):
            continue
        violating = delta > 0 if key in ("font_families", "page_count") else delta < 0
        if key in ("word_count", "whitespace"):
            violating = delta != 0
        if not violating:
            continue

        component = cost_by_key.get(key)
        if component:
            # points_lost is on the 0-100 structural scale; the composite weights it 15%.
            lost = float(component["points_lost"])
            points = round(lost * 0.15, 1)
            sub = component["sub_score"]
            severity = (
                SEVERITY_IMPORTANT if sub < 50
                else SEVERITY_POLISH
            )
            detail = (
                f" Scores {sub}/100 on this component, giving up "
                f"{lost:g} of {component['points_available']:g} layout points."
            )
        else:
            points, severity, detail = headroom, SEVERITY_POLISH, ""
        b.add(
            source_rule=rule,
            severity=severity,
            title=title,
            rationale=(
                f"Measured {metric.get('ACTUAL_VALUE')} against the SPO guideline of "
                f"{metric.get('GUIDELINE_VALUE')}. {metric.get('note', '')}".strip()
                + detail
            ),
            action=action,
            section="Document layout",
            pillar="Structural Layout",
            impact_points=points,
            evidence_regions=regions.get(key) or [],
            shared_impact=True,
        )


def _rule_unverified_companies(b: _Builder, unverified: List[str]) -> None:
    """
    Employers with no campus record.

    This used to report the name as unresolved and suggest it had been garbled in
    extraction, which read as an accusation against the candidate's own employer. The
    knowledge graph only covers firms that recruit here; sitting outside it is a fact
    about that coverage. So the organisation is sized instead, and the finding says what
    it is rather than what the graph failed to find.
    """
    if not unverified:
        return
    profiles = b.result.get("company_profiles") or {}

    described = []
    for name in unverified:
        profile = profiles.get(name) or {}
        label = profile.get("label")
        note = (profile.get("note") or "").strip()
        if not label or profile.get("band") == "unrecognised":
            described.append(f"{name} could not be sized from public information")
        elif note:
            described.append(f"{name} — {label.lower()}, {note.rstrip('.')}")
        else:
            described.append(f"{name} — {label.lower()}")

    b.add(
        source_rule="UNVERIFIED_COMPANY",
        severity=SEVERITY_POLISH,
        title="Employer has no campus recruiting record here",
        rationale=(
            "; ".join(described)
            + ". The recruiter graph only covers firms that run a process at IIT Kanpur, so "
            "this affects how the role is matched to recruiters, not how it is scored."
        ),
        action=(
            "Nothing to change. If the organisation is better known by another name, using "
            "that name helps it match against recruiter records."
        ),
        section="Work Experience",
        pillar="Work Experience",
        impact_points=0.0,
        informational=True,
        evidence_text=unverified[0],
    )


_SEVERITY_ORDER = {SEVERITY_HIGH: 0, SEVERITY_IMPORTANT: 1, SEVERITY_POLISH: 2}


def build_recommendations(
    result: Dict[str, Any],
    track: str,
    weights: Dict[str, float],
    unverified_companies: Optional[List[str]] = None,
) -> List[Dict[str, Any]]:
    b = _Builder(track, result, weights)
    _rule_academics(b)
    _rule_work_experience(b)
    _rule_projects(b)
    _rule_scope_bullets(b)
    _rule_weak_verbs(b)
    _rule_dilution(b)
    _rule_por(b)
    _rule_unverified_companies(b, unverified_companies or [])
    _rule_branch(b)
    _rule_layout(b)

    # A rule's severity reflects how bad the finding is in isolation; the track weighting
    # decides how much it can actually move. A SCOPE gap worth 1.9 points on QUANT (5%
    # weight) must not outrank a project gap worth 6.4, so severity is capped by leverage.
    for item in b.items:
        if item["severity"] == SEVERITY_HIGH and item["impact_points"] < 2.0:
            item["severity"] = SEVERITY_IMPORTANT
        if item["severity"] == SEVERITY_IMPORTANT and item["impact_points"] < 0.5:
            item["severity"] = SEVERITY_POLISH

    b.items.sort(key=lambda r: (_SEVERITY_ORDER[r["severity"]], -r["impact_points"]))
    return b.items
